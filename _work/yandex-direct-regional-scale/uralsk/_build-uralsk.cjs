function rep(a, b) {
  if (!html.includes(a)) {
    console.warn("MISS:", a.slice(0, 90).replace(/\n/g, " "));
    return false;
  }
  html = html.split(a).join(b);
  return true;
}

function repOnce(a, b) {
  const i = html.indexOf(a);
  if (i < 0) {
    console.warn("MISS once:", a.slice(0, 90).replace(/\n/g, " "));
    return false;
  }
  html = html.slice(0, i) + b + html.slice(i + a.length);
  return true;
}

