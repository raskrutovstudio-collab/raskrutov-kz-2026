const m = h.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/);
const schema = JSON.parse(m[1]);
const faq = schema["@graph"].find((x) => x["@type"] === "FAQPage");
const qRe = /id="yd-kks-faq-q(\d+)"[^>]*>([^<]+)</g;
const aRe = /id="yd-kks-faq-a(\d+)"[^>]*>([^<]+)</g;
const map = {};
let x;
while ((x = qRe.exec(h))) map[x[1]] = { ...(map[x[1]] || {}), q: x[2] };
while ((x = aRe.exec(h))) map[x[1]] = { ...(map[x[1]] || {}), a: x[2] };
faq.mainEntity = Object.keys(map)
  .sort((a, b) => +a - +b)
  .map((k) => ({
    "@type": "Question",
    name: map[k].q,
    acceptedAnswer: { "@type": "Answer", text: map[k].a },
  }));
h = h.replace(
  m[0],
  `<script type="application/ld+json">${JSON.stringify(schema)}</script>`
);

fs.writeFileSync(OUT, h);
