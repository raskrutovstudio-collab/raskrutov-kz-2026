function setBetween(idAttr, closeTag, text) {
  const i = html.indexOf(idAttr);
  if (i < 0) throw new Error("missing " + idAttr);
  const o = html.indexOf(">", i) + 1;
  const c = html.indexOf(closeTag, o);
  html = html.slice(0, o) + text + html.slice(c);
}

