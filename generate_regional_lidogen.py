def update_sitemap(slugs: list[str]) -> None:
    if not SITEMAP.exists():
        print("sitemap missing, skip")
        return
    xml = SITEMAP.read_text(encoding="utf-8")
    added = 0
    for slug in slugs:
        loc = f"https://raskrutov.kz/web-studiya/lidogeneratsiya/{slug}/"
        if loc in xml:
            continue
        entry = (
            f"  <url>\n"
            f"    <loc>{loc}</loc>\n"
            f"    <changefreq>weekly</changefreq>\n"
            f"    <priority>0.7</priority>\n"
            f"  </url>\n"
        )
        if "</urlset>" not in xml:
            raise SystemExit("sitemap has no urlset")
        xml = xml.replace("</urlset>", entry + "</urlset>")
        added += 1
    if added:
        SITEMAP.write_text(xml, encoding="utf-8")
    print(f"sitemap: +{added} urls")


